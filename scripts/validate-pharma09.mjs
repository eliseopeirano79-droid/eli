import assert from "node:assert/strict";
import fs from "node:fs";
import {fileURLToPath} from "node:url";
import {ELIX_CHAPTERS} from "../elix-content.js";
import {GUIDELINES_09,CHAPTERS_09} from "../elix-09-content.js";
import {extractConcepts09,splitIndications09,renderPK09,renderIndications09,validAssays09,modelStats09,renderAssay09,indicationState09,assayState09,exponentState09} from "../elix-pharma-labs.js";

const read=path=>JSON.parse(fs.readFileSync(fileURLToPath(new URL("../"+path,import.meta.url)),"utf8"));
const index=read("data/verified/index.json");
const f=index.molecules["CHEMBL13"]?.label?.file;
assert.ok(f,"Source-labeled metoprolol succinate is required");
const metoprolol=read("data/verified/"+f);
assert.match(metoprolol.product.generic.join(" "),/METOPROLOL SUCCINATE/);
assert.ok(metoprolol.sections?.dosage_and_administration?.length,"Original FDA dose section missing");
const concepts=extractConcepts09(metoprolol);
assert.ok(concepts.find(x=>x.id==="firstpass")?.quotes.length,"First pass excerpt must come from the imported label");
assert.ok(concepts.find(x=>x.id==="metabolism")?.quotes.some(x=>/CYP2D6/i.test(x)),"CYP2D6 appears in original source");
assert.ok(concepts.find(x=>x.id==="halfLife")?.quotes.length,"Actual elimination half-life not found");
assert.match(renderPK09(metoprolol),/Metabolismo di primo passaggio/);
const indications=splitIndications09(metoprolol);
for(const name of ["Hypertension","Angina Pectoris","Heart Failure"])assert.ok(indications.some(x=>x.title===name),"Missing metoprolol specific indication "+name);
const heart=indications.find(x=>x.title==="Heart Failure");
assert.ok(/12\.5|25 mg/i.test(heart.text),"Expected original HF labeled dosing not found");
indicationState09.set(f,heart.id);
const html=renderIndications09(metoprolol,f);
assert.match(html,/Heart Failure/);
assert.match(html,/METOPROLOL SUCCINATE/);
assert.match(html,/non è automaticamente il dosaggio italiano autorizzato/i);
assert.doesNotMatch(renderIndications09({sections:{},product:{}},f),/NaN/);
const sources=Object.entries(index.molecules).filter(([,v])=>v.activity).slice(0,160);
let example=null,record=null;
for(const [id,item] of sources) {
 const data=read("data/verified/"+item.activity.file);
 const options=validAssays09(data);
 if(options.length){example={id,item,data};record=options[0];break;}
}
assert.ok(example&&record,"No experimentally anchored assay available");
assert.ok(["Kd","EC50","IC50"].includes(record.type));
assert.equal(modelStats09(record,0).normalized,50);
assert.ok(modelStats09(record,1).normalized>90);
assert.ok(modelStats09(record,-1).normalized<10);
const chart=renderAssay09(example.data,example.item.activity.file);
assert.match(chart,/data-pk09-slider=/);
assert.match(chart,/NON descrive la dose somministrata/);
assert.match(chart,/Curva/);
assert.doesNotMatch(chart,/NaN|Infinity|<script/i);
assert.ok(validAssays09({records:[{type:"Ki",value:2,units:"nM",relation:"=",assay:"t",source:"https://example.com"}]}).length===0,"Ki is not interchangeable with measured EC50");
const malicious={sections:{pharmacokinetics:['Drug shows CYP2D6 <script>alert("x")</script> metabolism.']}};
const escaped=renderPK09(malicious);
assert.doesNotMatch(escaped,/<script>/);
assert.match(escaped,/&lt;script&gt;/);
assert.equal(ELIX_CHAPTERS.length,54);
assert.equal(CHAPTERS_09.length,12);
assert.equal(new Set(ELIX_CHAPTERS.map(x=>x.id)).size,54);
assert.equal(new Set(ELIX_CHAPTERS.map(x=>x.volume)).size,18);
assert.ok(CHAPTERS_09.every(x=>x.sections.length===4&&x.sections.every(s=>s.text.length>170)));
assert.equal(GUIDELINES_09.length,6);
assert.ok(GUIDELINES_09.every(x=>x.url.startsWith("https://")&&x.year>=2022));
const kdigo=GUIDELINES_09.find(x=>x.id==="kdigo-2024");
assert.ok(/consultazione/i.test(kdigo.status),"Draft KDIGO 2027 must not be represented as final");
const app=fs.readFileSync(fileURLToPath(new URL("../app.js",import.meta.url)),"utf8");
assert.equal((app.split("\n").find(x=>x.startsWith("const nav="))?.match(/\['(?:home|atlas|receptors|textbook|quiz)'/g)||[]).length,5);
const evidence=fs.readFileSync(fileURLToPath(new URL("../evidence-atlas.js",import.meta.url)),"utf8");
assert.match(evidence,/guidelineLinks09\(m,d\)/);
assert.match(evidence,/renderVerifiedByArea\(m,/);
const ui=fs.readFileSync(fileURLToPath(new URL("../elix-verified.js",import.meta.url)),"utf8");
assert.match(ui,/renderAssay09\(data,file\)/);
assert.match(ui,/renderPK09\(data\)/);
assert.match(ui,/renderIndications09\(data,file\)/);
const cache=fs.readFileSync(fileURLToPath(new URL("../sw.js",import.meta.url)),"utf8");
for(const asset of ["elix-09-content.js","elix-pharma-labs.js","elix-pharma-labs.css"])assert.ok(cache.includes(asset));
console.log("ELIX 0.9 PASS: 54 chapters; metoprolol sourced PK and 3 indication doses; Hill=1 assay curve; linked guidelines; source protections.");
