import assert from 'node:assert/strict';
import fs from 'node:fs';
import {fileURLToPath} from 'node:url';
import {schematicStructure,conceptualKind} from '../elix-structure-visuals.js';
import {createEvidenceAtlas} from '../evidence-atlas.js';

const readPath = path=>fs.readFileSync(fileURLToPath(new URL('../'+path,import.meta.url)),'utf8');
const readJSON=url=>JSON.parse(fs.readFileSync(fileURLToPath(url),'utf8'));
const catalog=readJSON(new URL('../data/catalog.json',import.meta.url));
const sample=catalog.molecules.find(m=>m.name==='ACETAMINOPHEN');
const without=catalog.molecules.find(m=>!m.smiles&&!/HEPARIN/.test(m.name));
assert.ok(sample&&sample.smiles,'Known chemical depiction case unavailable');
assert.ok(without,'Missing structure case not available');
assert.equal(conceptualKind({name:'ALPHA.1-PROTEINASE INHIBITOR HUMAN',type:'PROTEIN'}),'biologic');
assert.equal(conceptualKind({name:'HEPARIN',type:'UNKNOWN'}),'mixture');
assert.equal(conceptualKind({name:'EXPERIMENTAL XYZ',type:'SMALL MOLECULE'}),'compound');
const label=schematicStructure(without,true);
assert.match(label,/Visualizzazione 3D illustrativa/);
assert.match(label,/Non è una struttura molecolare reale/);
assert.match(label,/<svg viewBox=/);
assert.doesNotMatch(label,/PDB 7|struttura sperimentale verificata/);
const unsafe=schematicStructure({id:'X',name:'<script>alert(1)</script>',type:'PROTEIN'});
assert.doesNotMatch(unsafe,/<script>/);
assert.match(unsafe,/&lt;script&gt;/);
assert.equal(schematicStructure(without,true),schematicStructure(without,true),'Conceptual illustrations must be reproducible');
const hooks={};
globalThis.document={addEventListener(type,fn){(hooks[type]??=[]).push(fn);},getElementById(){return null}};
globalThis.location={hash:'#/atlas'};
const originalFetch=globalThis.fetch;
globalThis.fetch=async url=>({ok:true,json:async()=>readJSON(url)});
let ready;
const loaded=new Promise(resolve=>{ready=resolve;});
const atlas=createEvidenceAtlas({refresh(){ready();},legacyDrugs:[]});
await loaded;
const html=atlas.route('atlas');
assert.match(html,/ev-molecule-card/);
assert.match(html,/ev-chem-stage-source/,'Real 2D structures must use source depictions');
const item=atlas.route('molecule',sample.id);
assert.match(item,/ev-drug-sheet/);
assert.equal((item.match(/class="ev-topic"/g)||[]).length,6,'All information must be grouped into exactly six primary sections');
assert.equal((item.match(/data-ev-section=/g)||[]).length,6);
assert.match(item,/render|Come agisce|Assorbimento, metabolismo/);
assert.doesNotMatch(item,/<div class="vd-drug-data">/,'Do not dump all raw-data sections in one wall');
assert.match(item,/Nome internazionale \(EN\)/);
const missingHTML=atlas.route('molecule',without.id);
assert.match(missingHTML,/ev-concept-art/);
assert.match(missingHTML,/Visualizzazione 3D illustrativa/);
const target={matches:x=>x==='details[data-ev-section]',dataset:{evSection:sample.id+':adme'},open:true};
for(const fn of hooks.toggle||[])fn({target});
const opened=atlas.route('molecule',sample.id);
assert.ok(opened.includes('data-ev-section="'+sample.id+':adme" open'),'Open sections must persist through async refresh');
target.open=false;
for(const fn of hooks.toggle||[])fn({target});
const closed=atlas.route('molecule',sample.id);
assert.ok(!closed.includes('data-ev-section="'+sample.id+':adme" open'),'Sections must close normally');
const stylesheet=readPath('elix-clean-sheets.css');
assert.match(stylesheet,/\.ev-molecule-card>\.ev-chem\.mini \.ev-chem-stage/);
assert.match(stylesheet,/\.ev-drug-hero \.ev-chem-stage/);
assert.match(stylesheet,/\.ev-topic\[open\]/);
const sw=readPath('sw.js');
for(const file of ['elix-clean-sheets.css','elix-structure-visuals.js'])assert.ok(sw.includes(file),'Offline cache missing '+file);
const a=readPath('app.js');
assert.equal((a.split('\n').find(x=>x.startsWith('const nav='))?.match(/\['(?:home|atlas|receptors|textbook|quiz)'/g)||[]).length,5);
globalThis.fetch=originalFetch;
console.log('ELIX 0.10 PASS: larger real 2D structures, honest 3D-like missing visuals, six progressive sections, expand/collapse retention, five main tabs.');
