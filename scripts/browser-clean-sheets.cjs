const assert=require('node:assert/strict');
const fs=require('node:fs');
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
(async()=>{
 const browser=await chromium.launch({headless:true});
 const page=await browser.newPage({viewport:{width:1440,height:900},reducedMotion:'reduce'});
 const errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 const base='http://127.0.0.1:8765/';
 // Test remote-asset failures explicitly: the app must still show meaningful illustrations.
 await page.route('**/*',route=>route.request().url().startsWith(base)?route.continue():route.abort());
 await page.goto(base+'#/atlas');
 await page.waitForSelector('.ev-molecule-card');
 assert.equal(await page.locator('.topnav-link').count(),7);
 const tiles=page.locator('.ev-molecule-card');
 assert.ok(await tiles.count()>=30);
 const artwork=await tiles.first().locator('.ev-chem-stage').boundingBox();
 assert.ok(artwork.width>235&&artwork.height>=170,'Card imagery is still too small '+JSON.stringify(artwork));
 fs.mkdirSync('/tmp/elix-sheets',{recursive:true});
 await page.screenshot({path:'/tmp/elix-sheets/catalog-desktop.png',fullPage:false});
 const missingId=(()=>{const d=JSON.parse(fs.readFileSync('data/catalog.json','utf8'));return d.molecules.find(m=>!m.smiles&&!/HEPARIN/.test(m.name)).id;})();
 await page.goto(base+'#/molecule/'+missingId);
 await page.waitForSelector('.ev-concept-art');
 assert.match(await page.locator('.ev-concept-art').getAttribute('aria-label'),/Non è una struttura molecolare reale/);
 assert.equal(await page.locator('.ev-topic').count(),6);
 await page.screenshot({path:'/tmp/elix-sheets/concept-illustration.png',fullPage:false});
 await page.goto(base+'#/molecule/CHEMBL13');
 await page.waitForSelector('.ev-topic');
 assert.equal(await page.locator('.ev-topic').count(),6);
 assert.equal(await page.locator('details.ev-topic[open]').count(),0,'The initial page must be concise');
 await page.locator('details[data-ev-section="CHEMBL13:adme"]>summary').click();
 await page.waitForSelector('details[data-ev-section="CHEMBL13:adme"][open] .pk09-surface');
 await page.waitForFunction(()=>{const e=document.querySelector('details[data-ev-section="CHEMBL13:adme"]');return e?.open && !e.querySelector('.vd-loading');});
 assert.ok(await page.locator('details[data-ev-section="CHEMBL13:adme"]').evaluate(e=>e.open),'Expanded section closed after data load');
 const h=await page.locator('details[data-ev-section="CHEMBL13:adme"]').innerText();
 assert.match(h,/Metabolismo di primo passaggio/);
 await page.locator('details[data-ev-section="CHEMBL13:adme"]>summary').click();
 assert.equal(await page.locator('details[data-ev-section="CHEMBL13:adme"]').evaluate(e=>e.open),false);
 await page.locator('details[data-ev-section="CHEMBL13:dosage"]>summary').click();
 await page.waitForSelector('details[data-ev-section="CHEMBL13:dosage"][open] [data-pk09-indication]');
 await page.screenshot({path:'/tmp/elix-sheets/drug-desktop.png',fullPage:false});
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:'/tmp/elix-sheets/drug-mobile.png',fullPage:false});
 const widths=await page.evaluate(()=>({viewport:innerWidth,page:document.documentElement.scrollWidth}));
 assert.ok(widths.page<=widths.viewport+2,'Horizontal overflow: '+JSON.stringify(widths));
 const hero=await page.locator('.ev-drug-hero .ev-chem-stage').boundingBox();
 assert.ok(hero.width>290&&hero.height>=275,'Hero image on mobile is too small '+JSON.stringify(hero));
 await page.goto(base+'#/atlas');
 await page.waitForSelector('.ev-molecule-card');
 const mobileTile=await page.locator('.ev-molecule-card .ev-chem-stage').first().boundingBox();
 assert.ok(mobileTile.width>295&&mobileTile.height>=225,'Card illustration undersized on phone');
 assert.deepEqual(errors,[],'Browser runtime JS error');
 fs.writeFileSync('/tmp/elix-sheets/result.json',JSON.stringify({passed:true,desktopArtwork:artwork,mobileArtwork:mobileTile,hero,widths,errors},null,2));
 console.log('ELIX_10_BROWSER_PASS',JSON.stringify({desktopArtwork:artwork,mobileArtwork:mobileTile,widths}));
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1);});
