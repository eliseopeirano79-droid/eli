const assert=require('node:assert/strict');
const fs=require('node:fs');
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
(async()=>{
 const browser=await chromium.launch({headless:true});
 const page=await browser.newPage({viewport:{width:1365,height:950},reducedMotion:'reduce'});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 const base='http://127.0.0.1:8765/';
 // External services are not required for the local pre-imported dataset.
 await page.route('**/*',route=>route.request().url().startsWith(base)?route.continue():route.abort());
 await page.goto(base+'#/atlas');
 await page.waitForSelector('.vd-overview');
 assert.equal(await page.locator('.topnav-link').count(),7);
 await page.goto(base+'#/textbook');
 await page.waitForSelector('.ex-volume-grid');
 assert.ok((await page.locator('.ex-chapter-link').count())>=54);
 await page.goto(base+'#/textbook/posologia-per-indicazione');
 await page.waitForSelector('.ex-reading');
 assert.match(await page.locator('.ex-reading').innerText(),/4.1|posologia/);
 assert.ok(await page.locator('.ex-guides a').count()>0);
 await page.goto(base+'#/molecule/CHEMBL13');
 await page.waitForSelector('.vd-drug-data');
 await page.waitForSelector('[data-pk09-indication]');
 await page.waitForSelector('[data-pk09-slider]');
 assert.match(await page.locator('.pk09-surface').first().innerText(),/concentrazione/i);
 const opts=await page.locator('[data-pk09-indication] option').allTextContents();
 assert.ok(opts.some(x=>/Heart Failure/i.test(x)));
 await page.locator('[data-pk09-indication]').selectOption('sec3');
 assert.match(await page.locator('.pk09-source').innerText(),/Heart Failure/);
 const oldText=await page.locator('.pk09-numbers').innerText();
 await page.locator('[data-pk09-slider]').evaluate(el=>{el.value='1';el.dispatchEvent(new Event('input',{bubbles:true}));});
 const newText=await page.locator('.pk09-numbers').innerText();
 assert.notEqual(oldText,newText,'Concentration slider should recompute values');
 assert.match(await page.locator('.pk09-surface').first().innerText(),/NON descrive la dose/i);
 assert.match(await page.locator('.vd-drug-data').innerText(),/Metabolismo di primo passaggio/i);
 fs.mkdirSync('/tmp/elix-09-browser',{recursive:true});
 await page.screenshot({path:'/tmp/elix-09-browser/desktop.png',fullPage:false});
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:'/tmp/elix-09-browser/mobile.png',fullPage:false});
 const size=await page.evaluate(()=>({viewport:innerWidth,page:document.documentElement.scrollWidth}));
 assert.ok(size.page<=size.viewport+2,'Mobile overflow '+JSON.stringify(size));
 assert.deepEqual(errors,[],'JavaScript runtime errors');
 fs.writeFileSync('/tmp/elix-09-browser/result.json',JSON.stringify({passed:true,indications:opts,sliderChanged:true,size,errors},null,2));
 console.log('ELIX_09_BROWSER_PASS',JSON.stringify(size));
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
