const assert=require('node:assert/strict');
const fs=require('node:fs');
const {chromium}=require(process.env.PLAYWRIGHT_MODULE || 'playwright');
(async()=>{
 const index=JSON.parse(fs.readFileSync('data/verified/index.json','utf8'));
 const id=Object.keys(index.molecules).find(id=>index.molecules[id].activity&&index.molecules[id].label&&index.molecules[id].market);
 assert.ok(id,'Cross-source molecule missing');
 const browser=await chromium.launch({headless:true});
 const page=await browser.newPage({viewport:{width:1365,height:1000},reducedMotion:'reduce'});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 // Tests do not depend on external depiction/viewer servers; imported data is local.
 await page.route('**/*',route=>route.request().url().startsWith('http://127.0.0.1:8765/')?route.continue():route.abort());
 await page.goto('http://127.0.0.1:8765/#/atlas');
 await page.waitForSelector('.vd-overview');
 assert.equal(await page.locator('.topnav-link').count(),5,'Five primary sections only');
 await page.selectOption('#vd-data-kind','activity');
 assert.ok(await page.locator('.ev-molecule-card').count()>0);
 await page.selectOption('#vd-data-kind','market');
 await page.selectOption('#vd-order','price');
 assert.ok(await page.locator('.ev-molecule-card').count()>0);
 fs.mkdirSync('/tmp/elix-shots',{recursive:true});
 await page.screenshot({path:'/tmp/elix-shots/atlas-desktop.png',fullPage:false});
 await page.goto('http://127.0.0.1:8765/#/molecule/'+id);
 await page.waitForSelector('.vd-drug-data');
 await page.waitForFunction(()=>document.querySelectorAll('.vd-panel').length>=3 && document.querySelectorAll('.vd-loading').length===0);
 assert.ok(await page.locator('.vd-table tbody tr').count()>0);
 assert.ok((await page.locator('body').innerText()).includes('Prezzi reali per confezione'));
 assert.ok(await page.locator('.vd-label-sections details').count()>0);
 await page.locator('.vd-section-title').scrollIntoViewIfNeeded();
 await page.screenshot({path:'/tmp/elix-shots/molecule-desktop.png',fullPage:false});
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:'/tmp/elix-shots/molecule-mobile.png',fullPage:false});
 const widths=await page.evaluate(()=>({page:document.documentElement.scrollWidth,viewport:innerWidth}));
 assert.ok(widths.page<=widths.viewport+2,'Page overflows horizontally: '+JSON.stringify(widths));
 assert.deepEqual(errors,[],'JavaScript runtime errors');
 console.log('BROWSER_PASS',JSON.stringify({molecule:id,viewport:widths,errors}));
 fs.writeFileSync('/tmp/elix-shots/result.json',JSON.stringify({molecule:id,viewport:widths,errors,passed:true},null,2));
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
